/* NSE S/R Screener — static frontend.
   Reads pre-built JSON (data/screener.json + data/ohlcv/<SYMBOL>__<tf>.json)
   generated by build_site.py. No backend. Each ranked row already carries its
   line geometry, so clicking it only needs to fetch that stock's candles. */

const LC = LightweightCharts;

const state = {
  tf: "1d", key: null, chartType: "candles", cand: null, candles: null,
  // Live filters (defaults per spec). dAtrMax hides setups not near their line.
  filters: { dAtrMax: 0.5, minTouch: 6, minConf: 80, minTurnover: 5, setupType: "All" },
  sort: { col: "confidence", dir: "desc" },   // default: CONF descending
};
let ALL = [];          // every setup, from data/screener.json
let currentRows = [];  // rows currently shown (tf + filters + sort)

// Must match build_site.py's _safe(): non-alphanumeric -> "_"
const safeName = (s) => s.replace(/[^A-Za-z0-9]/g, "_");
const fmtSigned = (n) => (n == null ? "—" : (n >= 0 ? "+" : "") + n.toFixed(2));
const fmtPrice = (n) => (n == null ? "—" : n.toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 }));
const fmtVol = (n) => (n == null ? "—" : n.toFixed(1) + "×");
const rowKey = (c) => `${c.symbol}:${c.line_type}:${c.timeframe}:${c.value_now}`;

// Table columns — one source of truth for header, cells, and sorting.
// `num` columns render right-aligned + monospace; `l` columns left-aligned.
const COLUMNS = [
  { key: "symbol",       label: "Symbol", align: "l", get: (c) => c.symbol.replace("-EQ", ""), sort: (c) => c.symbol, cell: "l sym" },
  { key: "close",        label: "LTP",    num: true, get: (c) => fmtPrice(c.close),  sort: (c) => c.close ?? 0 },
  { key: "setup",        label: "Setup",  align: "l", get: (c) => c.setup,           sort: (c) => c.setup, cell: "l setup" },
  { key: "line_type",    label: "Line",   align: "l", get: (c) => (c.line_type === "trendline" ? "trend" : "horiz"), sort: (c) => c.line_type, cell: "l dim" },
  { key: "touches",      label: "Touch",  num: true, get: (c) => c.touches,          sort: (c) => c.touches },
  { key: "confidence",   label: "Conf",   num: true, get: (c) => Math.round(c.confidence) + "%", sort: (c) => c.confidence },
  { key: "distance_atr", label: "ΔATR",   num: true, get: (c) => fmtSigned(c.distance_atr), sort: (c) => c.distance_atr ?? 0 },
  { key: "vol_ratio",    label: "Vol×",   num: true, get: (c) => fmtVol(c.vol_ratio), sort: (c) => c.vol_ratio ?? -1,
    cellCls: (c) => (c.vol_ratio >= 1.5 ? "price-up" : "dim") },
];

// A row passes if it clears every active filter.
function passesFilters(c) {
  const f = state.filters;
  if (Math.abs(c.distance_atr ?? 0) > f.dAtrMax) return false;
  if (c.touches < f.minTouch) return false;
  if (c.confidence < f.minConf) return false;
  if ((c.turnover_cr ?? 0) < f.minTurnover) return false;
  if (f.setupType === "Breakouts")
    return c.setup === "Resistance Breakout" || c.setup === "Support Breakdown";
  if (f.setupType !== "All") return c.setup === f.setupType;
  return true;
}

function sortRows(rows) {
  const col = COLUMNS.find((x) => x.key === state.sort.col) || COLUMNS[5];
  const mul = state.sort.dir === "asc" ? 1 : -1;
  return rows.sort((a, b) => {
    const va = col.sort(a), vb = col.sort(b);
    if (typeof va === "string") return mul * va.localeCompare(vb);
    return mul * (va - vb);
  });
}

// ---- data load ---------------------------------------------------------
async function loadAll() {
  const res = await fetch("data/screener.json");
  ALL = await res.json();
  loadList();
}

// "Last generated" stamp (written by build_site.py into data/meta.json).
async function loadMeta() {
  try {
    const res = await fetch("data/meta.json");
    if (!res.ok) return;
    const m = await res.json();
    const bits = [];
    if (m.data_through) bits.push(`data through ${m.data_through}`);
    if (m.generated_at) bits.push(`built ${m.generated_at}`);
    document.getElementById("generated").textContent = bits.join("  ·  ");
  } catch (e) { /* older builds may not have meta.json */ }
}

// ---- ranked list -------------------------------------------------------
// Column headers: click to sort (toggle asc/desc), arrow on the active column.
function renderHead() {
  const head = document.getElementById("list-head");
  head.innerHTML = "";
  const tr = document.createElement("tr");
  COLUMNS.forEach((col) => {
    const th = document.createElement("th");
    if (col.align === "l") th.className = "l";
    const active = state.sort.col === col.key;
    const arrow = active ? (state.sort.dir === "asc" ? " ▲" : " ▼") : "";
    th.innerHTML = col.label + `<span class="arr">${arrow}</span>`;
    th.addEventListener("click", () => {
      if (state.sort.col === col.key) state.sort.dir = state.sort.dir === "asc" ? "desc" : "asc";
      else state.sort = { col: col.key, dir: col.num ? "desc" : "asc" };
      loadList();
    });
    tr.appendChild(th);
  });
  head.appendChild(tr);
}

function loadList() {
  const base = ALL.filter((c) => c.timeframe === state.tf);
  currentRows = sortRows(base.filter(passesFilters));

  renderHead();
  const body = document.getElementById("list-body");
  const empty = document.getElementById("list-empty");
  document.getElementById("shown-count").textContent = `${currentRows.length} of ${base.length} shown`;
  document.getElementById("count").textContent = "";
  body.innerHTML = "";

  if (!currentRows.length) {
    empty.style.display = "flex";
    empty.textContent = base.length ? "No setups match the filters — loosen them." : "No setups on this timeframe.";
    return;
  }
  empty.style.display = "none";

  currentRows.forEach((c) => {
    const key = rowKey(c);
    const tr = document.createElement("tr");
    tr.dataset.key = key;
    if (key === state.key) tr.classList.add("selected");
    tr.innerHTML = COLUMNS.map((col) => {
      const cls = [col.cell || "", col.cellCls ? col.cellCls(c) : ""].join(" ").trim();
      return `<td${cls ? ` class="${cls}"` : ""}>${col.get(c)}</td>`;
    }).join("");
    tr.addEventListener("click", () => selectRow(c));
    body.appendChild(tr);
  });

  // Keep the selection if it survived the filter, else open the top row.
  const stillHere = currentRows.find((c) => rowKey(c) === state.key);
  selectRow(stillHere || currentRows[0]);
}

// ---- filter bar --------------------------------------------------------
function setupFilters() {
  const bind = (id, key, parse) => {
    const el = document.getElementById(id);
    el.value = state.filters[key];
    el.addEventListener("input", () => {
      const v = parse(el.value);
      if (!Number.isNaN(v)) { state.filters[key] = v; loadList(); }
    });
  };
  bind("f-datr", "dAtrMax", parseFloat);
  bind("f-touch", "minTouch", (v) => parseInt(v, 10));
  bind("f-conf", "minConf", parseFloat);
  bind("f-turn", "minTurnover", parseFloat);

  document.querySelectorAll("#f-type button").forEach((btn) => {
    btn.addEventListener("click", () => {
      state.filters.setupType = btn.dataset.t;
      document.querySelectorAll("#f-type button").forEach((b) =>
        b.classList.toggle("active", b === btn));
      loadList();
    });
  });
}

function selectRow(cand) {
  state.key = rowKey(cand);
  document.querySelectorAll("table.list tr").forEach((tr) =>
    tr.classList.toggle("selected", tr.dataset.key === state.key)
  );
  loadChart(cand);
}

// ---- chart -------------------------------------------------------------
let chart = null;
let mainSeries = null;   // candlestick OR line, depending on state.chartType
let trendSeries = [];

function makeChart() {
  const el = document.getElementById("chart");
  chart = LC.createChart(el, {
    layout: {
      background: { type: "solid", color: "#0b0e13" },
      textColor: "#8a95a3",
      fontFamily: "ui-monospace, Menlo, monospace",
      fontSize: 11,
    },
    grid: { vertLines: { color: "#141a22" }, horzLines: { color: "#141a22" } },
    rightPriceScale: { borderColor: "#232b36" },
    timeScale: { borderColor: "#232b36", rightOffset: 6 },
    crosshair: { mode: LC.CrosshairMode.Normal },
    autoSize: false,
  });
  sizeChart();
  new ResizeObserver(sizeChart).observe(el);
}

function sizeChart() {
  const el = document.getElementById("chart");
  if (chart) chart.applyOptions({ width: el.clientWidth, height: el.clientHeight });
}

// Fetch a stock's candles, remember them, and draw. Called on row select.
async function loadChart(cand) {
  const res = await fetch(`data/ohlcv/${safeName(cand.symbol)}__${cand.timeframe}.json`);
  state.cand = cand;
  state.candles = await res.json();
  drawChart(true);   // new stock -> fit the view
}

// Draw state.candles + the setup line in the current chart type.
// `fit` refits the time scale; on a mere type toggle we keep the zoom.
function drawChart(fit) {
  const cand = state.cand, candles = state.candles;
  if (!cand || !candles) return;

  if (mainSeries) chart.removeSeries(mainSeries);
  trendSeries.forEach((s) => chart.removeSeries(s));
  trendSeries = [];

  if (state.chartType === "line") {
    mainSeries = chart.addLineSeries({
      color: "#9aa7b4", lineWidth: 2,
      priceLineVisible: false, lastValueVisible: true, crosshairMarkerVisible: true,
    });
    mainSeries.setData(candles.map((c) => ({ time: c.time, value: c.close })));
  } else {
    mainSeries = chart.addCandlestickSeries({
      upColor: "#2ea06a", downColor: "#e0554e",
      wickUpColor: "#2ea06a", wickDownColor: "#e0554e",
      borderVisible: false, priceLineVisible: false,
    });
    mainSeries.setData(candles);
  }

  // Draw the one setup line from the candidate's TRUE geometry (endpoints from
  // its slope) — for both trendlines and horizontals. Drawing a "horizontal"
  // flat when its touches actually drift would float the markers off the line.
  const emph = "#e6edf3";
  const first = cand.first_idx, last = cand.last_idx;
  const vn = cand.value_now, slope = cand.slope;
  if (candles[first] && candles[last]) {
    const s = chart.addLineSeries({
      color: emph, lineWidth: 2, lineStyle: LC.LineStyle.Solid,
      priceLineVisible: false, lastValueVisible: true, crosshairMarkerVisible: false,
    });
    s.setData([
      { time: candles[first].time, value: vn + slope * (first - last) },
      { time: candles[last].time, value: vn },
    ]);
    trendSeries.push(s);
  }

  // Touch-point markers.
  if (cand.touch_points && cand.touch_points.length) {
    mainSeries.setMarkers(
      cand.touch_points.map((tp) => ({
        time: tp.date, position: cand.role === "resistance" ? "aboveBar" : "belowBar",
        color: "#8a95a3", shape: "circle", size: 0.6,
      }))
    );
  }

  if (fit) chart.timeScale().fitContent();
  renderHeader(cand);
}

const STATE_TEXT = {
  "Support Reversal": "price holding above the support line",
  "Support Breakdown": "price has closed below the support line",
  "Resistance Reversal": "price holding below the resistance line",
  "Resistance Breakout": "price has closed above the resistance line",
};

function renderHeader(c) {
  const el = document.getElementById("chart-header-text");
  const sym = c.symbol.replace("-EQ", "");
  const sep = `<span class="h-meta dim">·</span>`;
  el.innerHTML = `
    <span class="h-sym">${sym}</span>
    <span class="h-meta ltp">${fmtPrice(c.close)}</span>
    <span class="h-setup">${c.setup}</span>
    ${sep}
    <span class="h-meta dim">${c.line_type}</span>
    ${sep}
    <span class="h-meta"><b>${c.touches}</b> touches</span>
    ${sep}
    <span class="h-meta">confidence <b>${Math.round(c.confidence)}%</b></span>
    ${sep}
    <span class="h-meta">fit <b>${c.fit_atr.toFixed(3)}</b></span>
    ${sep}
    <span class="h-meta">vol <b>${fmtVol(c.vol_ratio)}</b></span>
    ${sep}
    <span class="h-meta">turnover <b>${c.turnover_cr == null ? "—" : "₹" + c.turnover_cr + "cr"}</b></span>
    ${sep}
    <span class="h-meta">${STATE_TEXT[c.setup] || ""}</span>
    ${sep}
    <span class="h-meta"><b>${fmtSigned(c.distance_atr)}</b> ATR from line</span>
    ${sep}
    <span class="h-meta">last touch <b>${c.last_touch}</b></span>`;
}

// ---- timeframe toggle --------------------------------------------------
function setupToggle() {
  document.querySelectorAll("#tf-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => {
      if (btn.dataset.tf === state.tf) return;
      state.tf = btn.dataset.tf;
      document.querySelectorAll("#tf-toggle button").forEach((b) =>
        b.classList.toggle("active", b === btn)
      );
      loadList();
    });
  });
}

// ---- chart-type toggle (Candles / Line) --------------------------------
function setupChartTypeToggle() {
  document.querySelectorAll("#chart-type-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => {
      if (btn.dataset.ct === state.chartType) return;
      state.chartType = btn.dataset.ct;
      document.querySelectorAll("#chart-type-toggle button").forEach((b) =>
        b.classList.toggle("active", b === btn)
      );
      drawChart(false);   // keep the current zoom when just switching type
    });
  });
}

// ---- boot --------------------------------------------------------------
window.addEventListener("DOMContentLoaded", () => {
  makeChart();
  setupToggle();
  setupChartTypeToggle();
  setupFilters();
  const tf = new URLSearchParams(location.search).get("tf");
  if (["1d", "1w", "1m"].includes(tf)) {
    state.tf = tf;
    document.querySelectorAll("#tf-toggle button").forEach((b) =>
      b.classList.toggle("active", b.dataset.tf === tf)
    );
  }
  loadAll();
  loadMeta();
});
