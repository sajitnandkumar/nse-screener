/* NSE S/R Screener — static frontend.
   Reads pre-built JSON (data/screener.json + data/ohlcv/<SYMBOL>__<tf>.json)
   generated by build_site.py. No backend. Each ranked row already carries its
   line geometry, so clicking it only needs to fetch that stock's candles. */

const LC = LightweightCharts;

const state = { tf: "1d", key: null };
let ALL = [];          // every setup, from data/screener.json
let currentRows = [];  // the rows currently shown (filtered by timeframe)

// Must match build_site.py's _safe(): non-alphanumeric -> "_"
const safeName = (s) => s.replace(/[^A-Za-z0-9]/g, "_");
const fmtSigned = (n) => (n == null ? "—" : (n >= 0 ? "+" : "") + n.toFixed(2));
const rowKey = (c) => `${c.symbol}:${c.line_type}:${c.timeframe}:${c.value_now}`;

// ---- data load ---------------------------------------------------------
async function loadAll() {
  const res = await fetch("data/screener.json");
  ALL = await res.json();
  loadList();
}

// ---- ranked list -------------------------------------------------------
function loadList() {
  currentRows = ALL.filter((c) => c.timeframe === state.tf)
                   .sort((a, b) => b.confidence - a.confidence);

  const body = document.getElementById("list-body");
  const empty = document.getElementById("list-empty");
  document.getElementById("count").textContent = `${currentRows.length} setups`;
  body.innerHTML = "";

  if (!currentRows.length) {
    empty.style.display = "flex";
    empty.textContent = "No clean setups on this timeframe.";
    return;
  }
  empty.style.display = "none";

  currentRows.forEach((c, i) => {
    const key = rowKey(c);
    const tr = document.createElement("tr");
    tr.dataset.key = key;
    if (key === state.key) tr.classList.add("selected");
    tr.innerHTML = `
      <td class="l sym">${c.symbol.replace("-EQ", "")}</td>
      <td class="l setup">${c.setup}</td>
      <td class="l dim">${c.line_type === "trendline" ? "trend" : "horiz"}</td>
      <td>${c.touches}</td>
      <td>${Math.round(c.confidence)}%</td>
      <td>${fmtSigned(c.distance_atr)}</td>
      <td class="dim">${c.timeframe}</td>`;
    tr.addEventListener("click", () => selectRow(c));
    body.appendChild(tr);
  });

  // Keep the selection if it still exists in this timeframe, else open the top.
  const stillHere = currentRows.find((c) => rowKey(c) === state.key);
  selectRow(stillHere || currentRows[0]);
}

function selectRow(cand) {
  state.key = rowKey(cand);
  document.querySelectorAll("table.list tr").forEach((tr) =>
    tr.classList.toggle("selected", tr.dataset.key === state.key)
  );
  loadChart(cand);
}

// ---- chart -------------------------------------------------------------
let chart = null;
let candleSeries = null;
let trendSeries = [];

function makeChart() {
  const el = document.getElementById("chart");
  chart = LC.createChart(el, {
    layout: {
      background: { type: "solid", color: "#0b0e13" },
      textColor: "#8a95a3",
      fontFamily: "ui-monospace, Menlo, monospace",
      fontSize: 11,
    },
    grid: { vertLines: { color: "#141a22" }, horzLines: { color: "#141a22" } },
    rightPriceScale: { borderColor: "#232b36" },
    timeScale: { borderColor: "#232b36", rightOffset: 6 },
    crosshair: { mode: LC.CrosshairMode.Normal },
    autoSize: false,
  });
  sizeChart();
  new ResizeObserver(sizeChart).observe(el);
}

function sizeChart() {
  const el = document.getElementById("chart");
  if (chart) chart.applyOptions({ width: el.clientWidth, height: el.clientHeight });
}

async function loadChart(cand) {
  const res = await fetch(`data/ohlcv/${safeName(cand.symbol)}__${cand.timeframe}.json`);
  const candles = await res.json();

  if (candleSeries) chart.removeSeries(candleSeries);
  trendSeries.forEach((s) => chart.removeSeries(s));
  trendSeries = [];

  candleSeries = chart.addCandlestickSeries({
    upColor: "#2ea06a", downColor: "#e0554e",
    wickUpColor: "#2ea06a", wickDownColor: "#e0554e",
    borderVisible: false, priceLineVisible: false,
  });
  candleSeries.setData(candles);

  // Draw the one setup line from the candidate's geometry.
  const emph = "#e6edf3";
  const first = cand.first_idx, last = cand.last_idx;
  const vn = cand.value_now, slope = cand.slope;
  if (candles[first] && candles[last]) {
    if (cand.line_type === "horizontal") {
      candleSeries.createPriceLine({
        price: vn, color: emph, lineWidth: 2, lineStyle: LC.LineStyle.Solid,
        axisLabelVisible: true,
        title: `${cand.role === "resistance" ? "R" : "S"} x${cand.touches}`,
      });
    } else {
      const s = chart.addLineSeries({
        color: emph, lineWidth: 2, lineStyle: LC.LineStyle.Solid,
        priceLineVisible: false, lastValueVisible: false, crosshairMarkerVisible: false,
      });
      s.setData([
        { time: candles[first].time, value: vn + slope * (first - last) },
        { time: candles[last].time, value: vn },
      ]);
      trendSeries.push(s);
    }
  }

  // Touch-point markers.
  if (cand.touch_points && cand.touch_points.length) {
    candleSeries.setMarkers(
      cand.touch_points.map((tp) => ({
        time: tp.date, position: cand.role === "resistance" ? "aboveBar" : "belowBar",
        color: "#8a95a3", shape: "circle", size: 0.6,
      }))
    );
  }

  chart.timeScale().fitContent();
  renderHeader(cand);
}

const STATE_TEXT = {
  "Support Reversal": "price holding above the support line",
  "Support Breakdown": "price has closed below the support line",
  "Resistance Reversal": "price holding below the resistance line",
  "Resistance Breakout": "price has closed above the resistance line",
};

function renderHeader(c) {
  const el = document.getElementById("chart-header-text");
  const sym = c.symbol.replace("-EQ", "");
  const sep = `<span class="h-meta dim">·</span>`;
  el.innerHTML = `
    <span class="h-sym">${sym}</span>
    <span class="h-setup">${c.setup}</span>
    ${sep}
    <span class="h-meta dim">${c.line_type}</span>
    ${sep}
    <span class="h-meta"><b>${c.touches}</b> touches</span>
    ${sep}
    <span class="h-meta">confidence <b>${Math.round(c.confidence)}%</b></span>
    ${sep}
    <span class="h-meta">fit <b>${c.fit_atr.toFixed(3)}</b></span>
    ${sep}
    <span class="h-meta">${STATE_TEXT[c.setup] || ""}</span>
    ${sep}
    <span class="h-meta"><b>${fmtSigned(c.distance_atr)}</b> ATR from line</span>
    ${sep}
    <span class="h-meta">last touch <b>${c.last_touch}</b></span>`;
}

// ---- timeframe toggle --------------------------------------------------
function setupToggle() {
  document.querySelectorAll("#tf-toggle button").forEach((btn) => {
    btn.addEventListener("click", () => {
      if (btn.dataset.tf === state.tf) return;
      state.tf = btn.dataset.tf;
      document.querySelectorAll("#tf-toggle button").forEach((b) =>
        b.classList.toggle("active", b === btn)
      );
      loadList();
    });
  });
}

// ---- boot --------------------------------------------------------------
window.addEventListener("DOMContentLoaded", () => {
  makeChart();
  setupToggle();
  const tf = new URLSearchParams(location.search).get("tf");
  if (["1d", "1w", "1m"].includes(tf)) {
    state.tf = tf;
    document.querySelectorAll("#tf-toggle button").forEach((b) =>
      b.classList.toggle("active", b.dataset.tf === tf)
    );
  }
  loadAll();
});
